#!/usr/bin/env python3
"""Generate lib/resume.ts from the locked Ascend master resume.

The master's rule is that a surface selects and reorders bullets by ID and never
rewords them. Retyping bullets into TypeScript is how a site drifts from its
resume, so this file is generated instead. Edit the selection below, never the
output.

    python3 scripts/sync-resume.py [path/to/master.json]
"""
import json
import sys
from pathlib import Path

DEFAULT_MASTER = Path.home() / "Code/projects/koushik-docs/ascend-run-2026-10-31/master-v8.json"
OUT = Path(__file__).resolve().parent.parent / "lib" / "resume.ts"

# Bullet IDs per role, in render order. Every ID must exist in the master.
SELECTION = {
    "YahooP": ["PR1", "PR6", "PR7", "PR8", "PR2m", "PR3", "PR5m"],
    "Yahoo": ["Y4", "Y5", "Y6", "Y3", "Y8", "Y9", "Y11", "Y12", "Y14", "Y15"],
    "CYR3CON": ["C5", "C1", "C2"],
    "Infosys": ["I1"],
}
PROJECT_IDS = ["P1", "P2"]
SKILL_KEYS = ["AWS", "IAM", "DET", "CSPM", "REV", "AISEC", "AGENT", "HB", "TOXIC",
              "GCP", "CTR", "K8S", "MITRE", "PY", "TF", "LEAD", "PEOPLE"]


def ts(s: str) -> str:
    return json.dumps(s, ensure_ascii=False)


def main() -> None:
    master_path = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_MASTER
    m = json.loads(master_path.read_text())
    bullets = m["bullets"]
    work = {w["key"]: w for w in m["work"]}

    lines = [
        "/* GENERATED by scripts/sync-resume.py from the Ascend master resume",
        f"   (v{m['_meta']['master_version']}, locked {m['_meta']['locked_on']}). Do not edit by hand:",
        "   change the selection in the script and re-run it. Bullets are verbatim",
        "   from the master, which forbids rewording on any surface. */",
        "",
        "export interface Job { company: string; title: string; period: string; location: string; current: boolean; bullets: string[] }",
        "",
        f"export const basics = {{ name: {ts(m['basics']['name'])}, label: {ts(m['basics']['label'])}, location: {ts(m['basics']['location'])} }} as const;",
        "",
        f"export const summary = {ts(m['summaries']['S1']['text'])};",
        "",
        "export const jobs: Job[] = [",
    ]
    for key, ids in SELECTION.items():
        w = work[key]
        missing = [i for i in ids if i not in bullets]
        if missing:
            sys.exit(f"sync-resume: {key} selects unknown bullet ids {missing}")
        period = w["dates"].replace(" - ", " – ")
        lines.append("  {")
        lines.append(f"    company: {ts(w['company'])},")
        lines.append(f"    title: {ts(w['position'])},")
        lines.append(f"    period: {ts(period)},")
        lines.append(f"    location: {ts(w.get('location', ''))},")
        lines.append(f"    current: {'true' if 'Present' in w['dates'] else 'false'},")
        lines.append("    bullets: [")
        for i in ids:
            lines.append(f"      {ts(bullets[i]['text'])},")
        lines.append("    ],")
        lines.append("  },")
    lines.append("];")
    lines.append("")
    lines.append("export const projects: string[] = [")
    for i in PROJECT_IDS:
        lines.append(f"  {ts(bullets[i]['text'])},")
    lines.append("];")
    lines.append("")
    lines.append("export const skills: string[] = [")
    for k in SKILL_KEYS:
        lines.append(f"  {ts(m['skills_pool'][k])},")
    lines.append("];")
    lines.append("")
    lines.append("export const education = [")
    for e in m["education"]:
        lines.append(f"  {{ degree: {ts(e['studyType'])}, school: {ts(e['institution'])}, period: {ts(e['dates'].replace('-', '–'))} }},")
    lines.append("];")
    lines.append("")
    lines.append("/* Both certifications are lapsed and the master says so; shown with the date. */")
    lines.append("export const certs: string[] = [")
    for c in m["certifications"]:
        lines.append(f"  {ts(c)},")
    lines.append("];")
    lines.append("")
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT.relative_to(Path.cwd()) if OUT.is_relative_to(Path.cwd()) else OUT}")


if __name__ == "__main__":
    main()
